create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null,
 category text not null,
 description text,
 price numeric(10,2) not null check(price>=0),
 discount_price numeric(10,2),
 image_url text,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 customer_name text not null,
 customer_phone text not null,
 delivery_address text not null,
 reference text,
 payment_method text,
 change_for text,
 items jsonb not null,
 subtotal numeric(10,2) not null,
 total numeric(10,2) not null,
 status text not null default 'novo' check(status in ('novo','confirmado','em_preparo','saiu_entrega','concluido','cancelado')),
 created_at timestamptz not null default now()
);
alter table public.products enable row level security;
alter table public.orders enable row level security;
-- Cardápio pode ser lido publicamente; gravação exige login.
create policy "public read active products" on public.products for select using (active=true or auth.role()='authenticated');
create policy "admin manage products" on public.products for all to authenticated using (true) with check (true);
-- Cliente pode registrar pedido; apenas usuário autenticado pode consultar/alterar pedidos.
create policy "public create orders" on public.orders for insert to anon, authenticated with check (true);
create policy "admin read orders" on public.orders for select to authenticated using (true);
create policy "admin update orders" on public.orders for update to authenticated using (true) with check (true);
grant select on public.products to anon, authenticated;
grant insert,select,update on public.orders to anon,authenticated;
grant all on public.products to authenticated;
grant usage,select on all sequences in schema public to authenticated;
alter publication supabase_realtime add table public.orders;
