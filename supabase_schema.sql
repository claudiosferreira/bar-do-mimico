create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default '',
 phone text not null default '',
 username text,
 address text not null default '',
 reference text not null default '',
 role text not null default 'customer' check(role in ('customer','admin')),
 created_at timestamptz not null default now()
);
create unique index if not exists profiles_username_unique on public.profiles (lower(username)) where username is not null;
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null, category text not null, description text,
 price numeric(10,2) not null check(price>=0),
 discount_price numeric(10,2), image_url text,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.store_settings (
 id integer primary key default 1 check(id=1),
 is_open boolean not null default false,
 delivery_fee numeric(10,2) not null default 0 check(delivery_fee>=0),
 updated_at timestamptz not null default now()
);
insert into public.store_settings(id,is_open,delivery_fee) values(1,false,0) on conflict(id) do nothing;
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 customer_id uuid not null references auth.users(id),
 customer_name text not null, customer_phone text not null,
 delivery_address text not null, reference text,
 payment_method text, change_for text, items jsonb not null,
 subtotal numeric(10,2) not null, delivery_fee numeric(10,2) not null default 0,
 total numeric(10,2) not null,
 status text not null default 'novo' check(status in ('novo','confirmado','em_preparo','saiu_entrega','concluido','cancelado')),
 created_at timestamptz not null default now()
);
-- Criar perfil automaticamente no cadastro de usuário.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,full_name,phone,username,role)
 values(new.id,coalesce(new.raw_user_meta_data->>'full_name',''),coalesce(new.raw_user_meta_data->>'phone',''),nullif(new.raw_user_meta_data->>'username',''),'customer');
 return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.store_settings enable row level security;
alter table public.orders enable row level security;
-- Helpers de autorização para políticas de administrador.
create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;
grant execute on function public.is_admin() to anon, authenticated;
-- Perfis: cada cliente vê/edita apenas seu perfil; admin pode ver todos.
create policy "profile read own or admin" on public.profiles for select to authenticated using(id=auth.uid() or public.is_admin());
create policy "profile update own" on public.profiles for update to authenticated using(id=auth.uid()) with check(id=auth.uid() and role='customer');
create policy "profile insert own" on public.profiles for insert to authenticated with check(id=auth.uid() and role='customer');
-- Produtos e configurações: leitura pública, edição só admin.
create policy "products public read active" on public.products for select to anon,authenticated using(active=true or public.is_admin());
create policy "products admin all" on public.products for all to authenticated using(public.is_admin()) with check(public.is_admin());
create policy "settings public read" on public.store_settings for select to anon,authenticated using(true);
create policy "settings admin update" on public.store_settings for all to authenticated using(public.is_admin()) with check(public.is_admin());
-- Pedidos: clientes só criam e consultam os próprios; admin gerencia todos.
create policy "customer create own order" on public.orders for insert to authenticated with check(customer_id=auth.uid());
create policy "customer read own orders" on public.orders for select to authenticated using(customer_id=auth.uid() or public.is_admin());
create policy "admin update orders" on public.orders for update to authenticated using(public.is_admin()) with check(public.is_admin());
grant select on public.products,public.store_settings to anon,authenticated;
grant insert,update,delete on public.products to authenticated;
grant insert,select,update on public.profiles to authenticated;
grant select,insert,update on public.orders to authenticated;
grant usage,select on all sequences in schema public to authenticated;
-- Upload de fotos: bucket público para exibição; apenas admin pode enviar, alterar ou excluir.
insert into storage.buckets(id,name,public) values('product-images','product-images',true) on conflict(id) do nothing;
create policy "public view product photos" on storage.objects for select to anon,authenticated using(bucket_id='product-images');
create policy "admin upload product photos" on storage.objects for insert to authenticated with check(bucket_id='product-images' and public.is_admin());
create policy "admin update product photos" on storage.objects for update to authenticated using(bucket_id='product-images' and public.is_admin()) with check(bucket_id='product-images' and public.is_admin());
create policy "admin delete product photos" on storage.objects for delete to authenticated using(bucket_id='product-images' and public.is_admin());
